import { jsPDF } from "jspdf";

export const generatePDFReport = (patientData = {}, messages = []) => {
  const doc = new jsPDF();
  const dateStr = new Date().toLocaleDateString("en-IN", {
    day: "numeric",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });

  // Header Banner
  doc.setFillColor(14, 165, 233); // Sky Blue
  doc.rect(0, 0, 210, 30, "F");

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(20);
  doc.setFont("helvetica", "bold");
  doc.text("SANJEEVNI AI - CLINICAL INTAKE SUMMARY", 14, 18);

  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text(`Generated: ${dateStr}`, 14, 25);

  // Patient Info Box
  doc.setDrawColor(226, 232, 240);
  doc.setFillColor(248, 250, 252);
  doc.roundedRect(14, 36, 182, 36, 4, 4, "FD");

  doc.setTextColor(15, 23, 42);
  doc.setFontSize(11);
  doc.setFont("helvetica", "bold");
  doc.text("PATIENT DEMOGRAPHICS", 20, 44);

  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text(`Patient Name: ${patientData.name || "N/A"}`, 20, 52);
  doc.text(`Age: ${patientData.age || "N/A"} years`, 20, 58);
  doc.text(`Mobile: ${patientData.mobile || "N/A"}`, 20, 64);

  doc.text(`Patient ID: #${patientData.id || "REG-" + Math.floor(1000 + Math.random() * 9000)}`, 110, 52);
  doc.text(`ABHA Health ID: ${patientData.abhaId || "Not Registered"}`, 110, 58);
  doc.text(`Language: ${patientData.language || "Hindi/English"}`, 110, 64);

  // Pain Location & Severity Box
  doc.setFillColor(254, 242, 242);
  doc.setDrawColor(252, 165, 165);
  doc.roundedRect(14, 78, 182, 28, 4, 4, "FD");

  doc.setTextColor(185, 28, 28);
  doc.setFontSize(11);
  doc.setFont("helvetica", "bold");
  doc.text("SYMPTOM & PAIN MAPPING", 20, 86);

  doc.setTextColor(15, 23, 42);
  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text(`Reported Body Region: ${patientData.selectedBodyPart || "General Consultation"}`, 20, 94);
  doc.text(
    `Pain Severity Score: ${patientData.painSeverity ? `${patientData.painSeverity}/10 (${patientData.painSeverityLabel})` : "Not specified"}`,
    110,
    94
  );

  // Cumulative Past Visits Section (if returning patient)
  let yPos = 114;
  if (patientData.pastVisits && patientData.pastVisits.length > 0) {
    doc.setFontSize(11);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(30, 41, 59);
    doc.text(`PAST MEDICAL HISTORY (${patientData.pastVisits.length} Previous Visit(s))`, 14, yPos);
    yPos += 8;

    doc.setFontSize(9);
    patientData.pastVisits.forEach((visit, idx) => {
      doc.setFont("helvetica", "bold");
      doc.setTextColor(14, 165, 233);
      doc.text(`• Visit ${idx + 1} (${visit.date || 'Past'}): ${visit.selectedBodyPart || 'General'} (Severity ${visit.painSeverity || 5}/10)`, 16, yPos);
      yPos += 5;

      doc.setFont("helvetica", "normal");
      doc.setTextColor(71, 85, 105);
      const lines = doc.splitTextToSize(visit.summary || "No notes", 175);
      doc.text(lines, 20, yPos);
      yPos += lines.length * 4 + 4;
    });
    yPos += 4;
  }

  // Conversation Transcript Summary
  doc.setFontSize(12);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(15, 23, 42);
  doc.text("CLINICAL CONVERSATION LOG", 14, yPos);
  yPos += 8;
  doc.setFontSize(9);

  const displayMessages = messages.filter((m) => m.text).slice(-10);

  if (displayMessages.length === 0) {
    doc.setFont("helvetica", "italic");
    doc.setTextColor(100, 116, 139);
    doc.text("No transcripts recorded during session.", 14, yPos);
  } else {
    displayMessages.forEach((msg) => {
      const isUser = msg.role === "user" || msg._userMsg;
      const speaker = isUser ? "PATIENT: " : "SANJEEVNI AI DOCTOR: ";
      
      doc.setFont("helvetica", "bold");
      doc.setTextColor(isUser ? 30 : 14, isUser ? 41 : 165, isUser ? 59 : 233);

      const textLines = doc.splitTextToSize(`${speaker}${msg.text}`, 180);

      // Page overflow handler
      if (yPos + textLines.length * 5 > 270) {
        doc.addPage();
        yPos = 20;
      }

      doc.text(textLines, 14, yPos);
      yPos += textLines.length * 5 + 4;
    });
  }

  // Footer Disclaimer
  doc.setFontSize(8);
  doc.setFont("helvetica", "italic");
  doc.setTextColor(148, 163, 184);
  doc.text(
    "Disclaimer: This document is an automated pre-consultation intake summary generated by Sanjeevni AI for primary healthcare screening and does not constitute a final medical prescription.",
    14,
    285
  );

  // Save PDF
  const filename = `Sanjeevni_Clinical_Summary_${(patientData.name || "Patient").replace(/\s+/g, "_")}.pdf`;
  doc.save(filename);
};
